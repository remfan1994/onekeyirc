#!/usr/bin/env python3
"""Generate deterministic, dependency-free C lookup from editable JSON locales."""
from __future__ import annotations
import argparse
import json
import re
import unicodedata
from pathlib import Path

LANGS=('id','ms','tr','es','pt','fr','de','ru','it','ar')

def cquote(s: str) -> str:
    return json.dumps(s,ensure_ascii=False)

def unique_object_pairs(pairs):
    """Reject duplicate JSON keys; never silently let a later entry win."""
    values = {}
    for key, value in pairs:
        if key in values:
            raise ValueError(f'duplicate JSON translation key: {key}')
        values[key] = value
    return values


def read_catalog(path: Path):
    return json.loads(path.read_text(encoding='utf-8'),
                      object_pairs_hook=unique_object_pairs)


def render(project: Path) -> str:
    source = project/'i18n'
    keys=read_catalog(source/'en.json')
    assert isinstance(keys,list) and keys and len(set(keys))==len(keys)
    locales={}
    for lang in LANGS:
        catalog=read_catalog(source/(lang+'.json'))
        if not isinstance(catalog,dict) or set(catalog)!=set(keys):
            raise ValueError(f'{lang} catalog keys differ from English')
        for key, val in catalog.items():
            if not isinstance(val,str) or not val or any(x in val for x in ('\0','\r','\n','\x1b')):
                raise ValueError(f'{lang}: invalid translated value: {key}')
            if any(unicodedata.category(ch) in {'Cc', 'Cf', 'Cs'} for ch in val):
                raise ValueError(f'{lang}: forbidden control or direction mark: {key}')
            if re.search(r'%([0-9]*\$)?[-+0 #]*\d*[.\d]*[a-zA-Z]', val):
                raise ValueError(f'{lang}: format directive is not display text: {key}')
            if len(val.encode('utf-8'))>256:
                raise ValueError(f'{lang}: overlong translation: {key}')
        locales[lang]=catalog
    lines=[
        '/* GENERATED by tools/generate_localizations.py from the i18n language catalogs.',
        ' * Do not edit here: edit the UTF-8 catalogs and rerun the generator.',
        ' * Only display labels are translated. Protocol/configuration stay literal. */',
        '#ifndef IRC_L10N_H',
        '#define IRC_L10N_H',
        '/* Defined once by src/idle_setup.c, also shared by full vipirc. */',
        'const char *irc_tr(const char *english);',
        '#ifdef IRC_L10N_IMPLEMENTATION',
        '/* Optional English-only build: CPPFLAGS=-DIRC_DISABLE_LOCALIZATION ./configure */',
        '#ifdef IRC_DISABLE_LOCALIZATION',
        'const char *irc_tr(const char *english) { return english; }',
        '#else',
        '#include <stddef.h>',
        '#include <stdlib.h>',
        '#include <string.h>',
        'typedef struct { const char *source; const char *value; } IrcTranslation;',
        'static const char *irc_ui_language(void)',
        '{',
        '    /* Respect the launched program before the compatible shared fallback. */',
        '#ifdef ONEKEY_ONLY',
        '    const char *s = getenv("ONEKEYIRC_LANG");',
        '    if (!s || !*s) s = getenv("VIPIRC_LANG");',
        '#else',
        '    const char *s = getenv("VIPIRC_LANG");',
        '    if (!s || !*s) s = getenv("ONEKEYIRC_LANG");',
        '#endif',
        '    if (!s || !*s) s = getenv("LC_ALL");',
        '    if (!s || !*s) s = getenv("LC_MESSAGES");',
        '    if (!s || !*s) s = getenv("LANG");',
        '    return s && *s ? s : "en";',
        '}',
        'const char *irc_tr(const char *english)',
        '{',
        '    if (!english) return NULL;',
        '    const char *lang = irc_ui_language();',
        '    const IrcTranslation *entries = NULL;',
        '    size_t count = 0;',
    ]
    for lang,catalog in locales.items():
        table=f'irc_{lang}_table'
        entries=sorted(catalog.items(),key=lambda x:x[0])
        decl=['static const IrcTranslation '+table+'[] = {']
        decl+=['    {'+cquote(k)+', '+cquote(v)+'},' for k,v in entries]
        decl+=['};']
        # Insert tables before function, in deterministic language order.
        insert_at=lines.index('static const char *irc_ui_language(void)')
        lines[insert_at:insert_at]=decl
    for index,lang in enumerate(LANGS):
        condition=f"lang[0] == '{lang[0]}' && lang[1] == '{lang[1]}' && " + "(lang[2] == '\\0' || lang[2] == '_' || lang[2] == '-' || lang[2] == '.' || lang[2] == '@')"
        lines.append(('    if' if index==0 else '    else if')+' ('+condition+') {')
        lines.append(f'        entries = irc_{lang}_table;')
        lines.append(f'        count = sizeof irc_{lang}_table / sizeof irc_{lang}_table[0];')
        lines.append('    }')
    lines += [
        '    if (!entries) return english;',
        '    size_t first = 0, last = count;',
        '    while (first < last) {',
        '        size_t middle = first + (last - first) / 2;',
        '        int comparison = strcmp(english, entries[middle].source);',
        '        if (comparison == 0) return entries[middle].value;',
        '        if (comparison < 0) last = middle;',
        '        else first = middle + 1;',
        '    }',
        '    return english;',
        '}',
        '#endif /* IRC_DISABLE_LOCALIZATION */',
        '#endif /* IRC_L10N_IMPLEMENTATION */',
        '#endif /* IRC_L10N_H */',
    ]
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    ap=argparse.ArgumentParser()
    ap.add_argument('--check',action='store_true',help='fail if generated header differs')
    args=ap.parse_args()
    project=Path(__file__).resolve().parent.parent
    output=project/'src/l10n.h'
    content=render(project)
    if args.check:
        if output.read_text(encoding='utf-8')!=content:
            raise SystemExit('Localization catalog/header mismatch; run python3 tools/generate_localizations.py')
        print('Localization catalogs and generated header: PASS')
    else:
        output.write_text(content,encoding='utf-8')
        print(f'Generated {output}')
