def _escape(text: str) -> str:
    text = text.replace("\\", r"\e").replace("-", r"\-")
    return "\n".join((r"\&" + line if line.startswith((".", "'")) else line)
                     for line in text.split("\n"))


def _heading(title: str, level: str = "SH") -> str:
    return "." + level + ' "' + _escape(title.replace('"', "'")) + '"\n'


def _paragraphs(text: str) -> str:
    chunks = []
    for paragraph in text.strip().split("\n\n"):
        if not paragraph.strip():
            continue
        lines = paragraph.splitlines()
        if any(line.startswith((" ", "\t")) for line in lines):
            chunks.append(".PP\n.RS 4\n.nf\n" + _escape(textwrap.dedent(paragraph)) + "\n.fi\n.RE\n")
        else:
            chunks.append(".PP\n" + _escape(" ".join(line.strip() for line in lines)) + "\n")
    return "".join(chunks)


def _full_body(manual: str) -> str:
    # The first line is the title, already represented by NAME and the TH header.
    body = manual.split("\n", 1)[1]
    headings = list(re.finditer(r"^([A-Z][A-Z0-9 ,/()\-]*)\n", body, re.M))
    if not headings:
        raise ValueError("MANUAL.txt has no uppercase section headings")
    result = [_heading("DESCRIPTION"), _paragraphs(body[:headings[0].start()])]
    for i, match in enumerate(headings):
        end = headings[i + 1].start() if i + 1 < len(headings) else len(body)
        result += [_heading(match.group(1)), _paragraphs(body[match.end():end])]
    return "".join(result)


def _native_body(manual: str) -> str:
    lines = manual.splitlines()[1:]
    result = [_heading("IN-PROGRAM REFERENCE")]
    command_reference = False
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line:
            i += 1
            continue
        if i + 1 < len(lines) and re.fullmatch(r"-{3,72}", lines[i + 1]):
            if line.startswith("/"):
                if not command_reference:
                    result.append(_heading("COMMAND REFERENCE"))
                    command_reference = True
                result.append(_heading(line, "SS"))
            else:
                result.append(_heading(line.upper()))
            i += 2
            continue
        if line.startswith("Usage: "):
            result += [".PP\n.B Usage:\n", _paragraphs(line[7:])]
            i += 1
            continue
        if line == "Examples:":
            result.append(".PP\n.B Examples:\n")
            i += 1
            example = []
            while i < len(lines) and lines[i]:
                example.append(lines[i])
                i += 1
            result.append(".RS 4\n.nf\n" + _escape("\n".join(example)) + "\n.fi\n.RE\n")
            continue
        if line.startswith("  /"):
            rows = []
            while i < len(lines) and lines[i].startswith("  /"):
                rows.append(lines[i].lstrip())
                i += 1
            result.append(".PP\n.RS 4\n.nf\n" + _escape("\n".join(rows)) + "\n.fi\n.RE\n")
            continue
        result.append(_paragraphs(line))
        i += 1
    return "".join(result)


def render_man(program: str, version: str, manual_text: str, cli_help_text: str) -> str:
    """Return deterministic ASCII man(7) source from verified documentation inputs."""
    if program not in ("vipirc", "onekeyirc"):
        raise ValueError("unsupported product: " + program)
    for name, value in (("version", version), ("manual", manual_text), ("CLI help", cli_help_text)):
        if not value or not value.isascii():
            raise ValueError(name + " must be nonempty ASCII")
    result = ['.\\" Generated by scripts/sync_docs.py; edit canonical documentation sources.\n',
              '.TH ' + program.upper() + ' 1 "' + DOC_DATE + '" "' + program + ' ' + version + '" "User Commands"\n',
              ".nh\n.ad l\n", _heading("NAME"),
              program + r" \- " + ("terminal IRC client" if program == "vipirc" else "command-oriented terminal IRC client") + "\n",
              _heading("SYNOPSIS"), ".B " + program + "\n.RI [ OPTION ... ]\n.br\n",
              ".B " + program + r" \-\-resume" + "\n.RI [ NUMBER | SOCKET ]\n.br\n",
              ".B " + program + r" \-\-sessions" + "\n.br\n",
              ".B " + program + r" \-\-detach\-session" + "\n.I NUMBER\n.br\n",
              ".B " + program + r" \-\-close\-session" + "\n.I NUMBER\n"]
    if program == "vipirc":
        help_flags = set(re.findall(r"--[a-z][a-z-]*", cli_help_text))
        missing = help_flags - set(re.findall(r"--[a-z][a-z-]*", manual_text))
        if missing:
            raise ValueError("CLI options missing from MANUAL.txt: " + ", ".join(sorted(missing)))
        result.append(_full_body(manual_text))
    else:
        documented = "\n".join(label for label, _ in ONEKEY_OPTIONS)
        help_flags = set(re.findall(r"--[a-z][a-z-]*", cli_help_text))
        missing = help_flags - set(re.findall(r"--[a-z][a-z-]*", documented))
        if missing:
            raise ValueError("CLI options missing from expanded man reference: " + ", ".join(sorted(missing)))
        result += [_heading("DESCRIPTION"), _paragraphs(ONEKEY_START), _heading("OPTIONS")]
        for label, description in ONEKEY_OPTIONS:
            result += [".TP\n.B " + _escape(label) + "\n", _escape(description) + "\n"]
        result += [_paragraphs(ONEKEY_OPTION_RULES), _heading("FILES AND ENVIRONMENT"),
                   _paragraphs(ONEKEY_FILES), _heading("EXIT STATUS"), _paragraphs(ONEKEY_EXIT),
                   _native_body(manual_text), _heading("SEE ALSO"),
                   "README.md, MANUAL.txt, INSTALL, SECURITY.md, DESIGN.md,\n",
                   "doc/BOUNCERS.txt, doc/SESSION-CONTROLS.txt, doc/OPENBSD-VPS.txt.\n",
                   _heading("AUTHORS AND LICENSE"),
                   "An application of ThatIAm.vip (www.thatiam.vip), designed by remfan1994.\n",
                   "Source is available under the included IALA (Insha-Allah License Agreement);\n",
                   "see LICENSE.md and NOTICE for full terms and dependency notices.\n"]
    text = "".join(result)
    assert text.isascii() and text.endswith("\n")
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path,
                        help="trusted binary built from this source tree")
    parser.add_argument("--embedded-only", action="store_true",
                        help="vipirc: generate C/plain full manual before building")
    parser.add_argument("--check", action="store_true",
                        help="verify outputs without modifying any files")
    args = parser.parse_args()
    product = "vipirc" if (ROOT / "src/manual.c").exists() else "onekeyirc"
    macro = "VIPIRC_VERSION" if product == "vipirc" else "ONEKEY_VERSION"
    match = re.search(r'^#define\s+' + macro + r'\s+"([0-9.]+)"',
                      (ROOT / "src/app.h").read_text(encoding="ascii"), re.M)
    if not match:
        raise ValueError(f"cannot read {macro} from src/app.h")
    version = match.group(1)
    outputs = {}
    if product == "vipirc":
        manual = ascii_text((ROOT / "MANUAL.txt").read_bytes(), "MANUAL.txt")
        if not manual.startswith(f"vipirc {version} - "):
            raise ValueError("MANUAL.txt title does not match src/app.h")
        limit = re.search(r'^#define\s+APP_HELP_LINES\s+(\d+)',
                          (ROOT / "src/app.h").read_text(encoding="ascii"), re.M)
        if not limit or len(manual.splitlines()) > int(limit.group(1)):
            raise ValueError("MANUAL.txt exceeds the minimum Help-buffer capacity; "
                             "compact the manual before generating it")
        outputs["src/manual.c"] = embedded_manual(manual)
        outputs["doc/manual.txt"] = manual
    elif args.embedded_only:
        raise ValueError("--embedded-only applies to vipirc; onekeyirc uses compiled help")
    if args.embedded_only:
        if args.binary:
            raise ValueError("--embedded-only cannot be combined with --binary")
        publish(outputs, args.check)
        print(f"{product}: embedded manual {'checked' if args.check else 'synchronized'}")
        return

    binary = (args.binary or ROOT / product).resolve()
    if not binary.is_file():
        raise ValueError(f"build {product} first (missing {binary})")
    actual_version = run_information(binary, ["--version"]).splitlines()[0]
    if actual_version != f"{product} {version}":
        raise ValueError(f"binary version mismatch: {actual_version!r}; rebuild {product}")
    compiled = run_information(binary, ["--manual"])
    cli_help = run_information(binary, ["--help"])
    if product == "vipirc":
        if compiled != manual:
            raise ValueError("binary full manual differs from MANUAL.txt; run "
                             "--embedded-only, rebuild vipirc, then retry")
        outputs["doc/vipirc-idle-manual.txt"] = run_information(binary, ["-i", "--manual"])
    else:
        outputs["MANUAL.txt"] = compiled
        outputs["doc/onekeyirc-manual.txt"] = compiled
    outputs[f"doc/{product}.1"] = render_man(product, version, compiled, cli_help)
    publish(outputs, args.check)
    print(f"{product}: generated documentation {'checked' if args.check else 'synchronized'}")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        print(f"documentation: {error}", file=sys.stderr)
        sys.exit(1)
