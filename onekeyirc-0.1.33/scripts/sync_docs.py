#!/usr/bin/env python3
"""Refresh/check shipped manuals using their authoritative source and binary.

Python is a documentation-maintenance dependency, not a build/runtime
dependency. Release archives include all generated C and text outputs.
Only invoke this tool with a trusted binary built from this source tree.
"""

import argparse
import json
import re
import subprocess
import sys
import textwrap
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def ascii_text(data, label):
    """Reject binary/control text before producing C, troff or plain exports."""
    if isinstance(data, bytes):
        try:
            data = data.decode("ascii")
        except UnicodeDecodeError as exc:
            raise ValueError(f"{label}: documentation must be ASCII") from exc
    if any(ord(char) > 126 or (ord(char) < 32 and char not in "\n\t")
           for char in data):
        raise ValueError(f"{label}: unexpected control/non-ASCII character")
    if not data.endswith("\n"):
        raise ValueError(f"{label}: missing final newline")
    return data


def embedded_manual(manual):
    """One string per display line; no separate manually edited C transcript."""
    lines = ["/* Generated by scripts/sync_docs.py from MANUAL.txt. */",
             "#include <stddef.h>", '#include "manual.h"', "",
             "const char *const vipirc_manual[] = {"]
    for line in manual.splitlines():
        # Escape '?' as well so a future '??/' example cannot become a C
        # trigraph under a toolchain that enables those translations.
        escaped = json.dumps(line, ensure_ascii=True).replace("?", "\\?")
        lines.append(f"    {escaped},")
    lines.extend(["    NULL", "};", ""])
    return "\n".join(lines)


def run_information(binary, arguments):
    result = subprocess.run([str(binary), *arguments], cwd=ROOT,
                            stdin=subprocess.DEVNULL, capture_output=True,
                            timeout=15, check=False)
    if result.returncode != 0 or result.stderr:
        raise ValueError(f"{binary.name} {' '.join(arguments)} failed "
                         f"(exit {result.returncode}): "
                         f"{result.stderr.decode('ascii', errors='replace').strip()}")
    return ascii_text(result.stdout, " ".join(arguments))


def publish(outputs, check):
    stale = []
    for relative, content in outputs.items():
        content = ascii_text(content, relative).encode("ascii")
        path = ROOT / relative
        if path.is_file() and path.read_bytes() == content:
            continue
        if check:
            stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            print(f"updated {relative}")
    if stale:
        raise ValueError("stale/missing generated documentation: " +
                         ", ".join(stale) + "; run make docs and rebuild")


